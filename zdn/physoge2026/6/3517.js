(function () {
	'use strict';
	retryWhileError(function () {
		NAinfo.requireApiVersion(0, 2);

		let tTotal = sl(2, 10, 1);
		let n = sl(1, tTotal, 1);
		let g = 10;

		let path = g * (2 * n - 1) / 2;

		let ordinalsV = [
			'первую', 'вторую', 'третью', 'четвёртую', 'пятую',
			'шестую', 'седьмую', 'восьмую', 'девятую', 'десятую'
		];

		let ordinalName = ordinalsV[n - 1];

		genAssert(path.isAlmostInteger(), 'Путь не целое число');

		NAtask.setTask({
			text: 'Тело свободно падает по вертикали с нулевой начальной скоростью ' +
				'в течение ' + tTotal + ' с. Сопротивление воздуха пренебрежимо мало. ' +
				'Какой путь пройдёт тело за ' + ordinalName + ' секунду от начала движения? ' +
				'Ответ запишите в метрах.',
			answers: path,
			analys: 'Путь, пройденный телом за время $t$ при свободном падении без начальной скорости, ' +
				'определяется формулой $s = \\frac{gt^2}{2}$. ' +
				'Найдём путь, пройденный телом за ' + n + ' с и за ' + (n - 1) + ' с: ' +
				'$$s_{' + n + '} = \\frac{' + g + ' \\cdot ' + n + '^2}{2} = ' +
				(g * n * n / 2) + ' \\text{ м}' +
				(n > 1 ? ', \\quad s_{' + (n - 1) + '} = \\frac{' + g + ' \\cdot ' + (n - 1) + '^2}{2} = ' +
				(g * (n - 1) * (n - 1) / 2) + ' \\text{ м}' : '') +
				'.$$ ' +
				'Путь за ' + ordinalName + ' секунду равен ' +
				(n > 1 ? 'разности этих величин: ' : 'этому значению: ') +
				'$$s = ' +
				(n > 1 ? (g * n * n / 2) + ' - ' + (g * (n - 1) * (n - 1) / 2) + ' = ' : '') +
				path + ' \\text{ м}.$$ ' +
				'Таким образом, за ' + ordinalName + ' секунду тело пройдёт путь $' + path + '$ м.',
		});
	}, 1000);
})();
