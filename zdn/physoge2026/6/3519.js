(function () {
	'use strict';
	retryWhileError(function () {
		NAinfo.requireApiVersion(0, 2);

		let g = 10;
		let n = sl(2, 9, 1); // номер секунды, за которую спрашиваем приращение скорости

		let ordinalsV = [
			'первую', 'вторую', 'третью', 'четвёртую', 'пятую',
			'шестую', 'седьмую', 'восьмую', 'девятую', 'десятую'
		];
		let ordinalName = ordinalsV[n - 1];

		// Приращение модуля скорости за любую отдельную секунду свободного падения
		// равно g*1 с и не зависит от номера секунды.
		let dv = g;

		NAtask.setTask({
			text: 'Тело свободно падает с нулевой начальной скоростью. ' +
				'Сопротивление воздуха пренебрежимо мало. ' +
				'На сколько увеличится модуль скорости тела за ' + ordinalName +
				' секунду от начала движения? Ответ запишите в метрах в секунду.',
			answers: dv,
			analys: 'При свободном падении без начальной скорости модуль скорости растёт по закону ' +
				'$v = gt$. За ' + n + ' с от начала движения скорость равна ' +
				'$v_{' + n + '} = ' + g + ' \\cdot ' + n + ' = ' + (g * n) + '$ м/с, ' +
				'а за ' + (n - 1) + ' с — $v_{' + (n - 1) + '} = ' + g + ' \\cdot ' + (n - 1) + ' = ' + (g * (n - 1)) + '$ м/с. ' +
				'Приращение скорости за ' + ordinalName + ' секунду: ' +
				'$$\\Delta v = v_{' + n + '} - v_{' + (n - 1) + '} = ' + (g * n) + ' - ' + (g * (n - 1)) + ' = ' + dv + ' \\text{ м/с}.$$ ' +
				'Это приращение одинаково для любой отдельной секунды падения и равно $g = ' + g + '$ м/с.',
		});
	}, 1000);
})();
