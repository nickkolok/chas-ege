(function () {
	'use strict';
	retryWhileError(function () {
		NAinfo.requireApiVersion(0, 2);

		let V = sl(1, 20);
		let rho;
		do {
			rho = sl(500, 15000, 500);
		} while ((rho * V) % 1000 !== 0);
		let m = rho * V / 1000;

		NAtask.setTask({
			text: 'Определите плотность жидкого вещества, целиком заполняющего ведро ёмкостью $' + V + '$ л, ' +
				'если масса вещества равна $' + m + '$ кг. Ответ дайте в кг/м$^3$.',
			answers: rho,
			analys: 'Плотность вещества определяется как отношение его массы к объёму: ' +
				'$$\\rho = \\frac{m}{V}.$$ ' +
				'Переведём объём в СИ: $' + V + '$ л = $' + V + ' \\cdot 10^{-3}$ м$^3$ = $' + (V / 1000) + '$ м$^3$. ' +
				'Тогда плотность равна: ' +
				'$$\\rho = \\frac{' + m + '}{' + (V / 1000) + '} = ' + rho + ' \\text{ кг/м}^3.$$ ' +
				'Таким образом, плотность вещества составляет $' + rho + '$ кг/м$^3$.',
		});
	}, 1000);
})();
