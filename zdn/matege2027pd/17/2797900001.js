(function() { 'use strict'; retryWhileError(function() {
    let r = [1, 2, 5, 10].iz(); // внутреннее сопротивление, Ом
    let k = sl(5, 25);          // ток в согласованной нагрузке: k = ε/(2r), А
    let e = 2 * r * k;          // ЭДС, В — всегда целое и «круглое»
    let ans = r * k * k;        // P_max = e*e/(4r), Вт — всегда целое
    genAssertZ1000(ans);

    NAtask.setTask({
        text: `На заводе имеется генератор с ЭДС $\\varepsilon$ = ${e} В и внутренним сопротивлением $r$ = ${r} Ом.
        Инженер подключает к генератору нагрузку, используя реостат, чтобы установить сопротивление нагрузки $R$ (в омах).
        Сила тока в цепи (в амперах) определяется законом Ома: $I = \\frac{\\varepsilon}{r + R}$. Тепловая мощность (в ваттах),
        выделяемая в нагрузке, может быть рассчитана по формуле Джоуля—Ленца: $P = I^2 R$.
        Какова максимальная тепловая мощность $P$, которая может быть выделена нагрузкой? Ответ дайте в ваттах.`,
        answers: ans,
        analys: `Мощность $P = \\frac{\\varepsilon^2 R}{(r + R)^2}$ достигает максимума при $R = r = ${r}$ Ом,
        откуда $P = \\frac{\\varepsilon^2}{4r} = \\frac{${e}^2}{4 \\cdot ${r}} = ${ans}$ Вт.`,
        authors: ['Nadezhda'],
    });
    NAtask.modifiers.allDecimalsToStandard(/*true*/);
}, 2000);})();
