(function () {
	'use strict';
	retryWhileError(function () {
		NAinfo.requireApiVersion(0, 2);

		let m = sl(100, 500, 50);
		let k = sl(100, 1000, 100);
		
		let m_kg = m / 1000;
		let g = 10;
		let F = m_kg * g;
		
		let x = F / k;
		
		genAssert(x.toString().split('.')[1] === undefined || x.toString().split('.')[1].length <= 4, "Удлинение имеет слишком много знаков после запятой");

		NAtask.setTask({
			text: 'Груз массой ' + m + ' г подвесили к пружине. Длина пружины при этом увеличилась на ' + x + ' м. ' +
				'Чему равна жёсткость пружины? Ответ дайте в Н/м.',
			answers: k,
			analys: 'По условию груз находится в равновесии, поэтому сила тяжести уравновешивается силой упругости пружины (закон Гука): ' +
				'$$mg = kx$$ ' +
				'Выразим жёсткость пружины: ' +
				'$$k = \\frac{mg}{x}$$ ' +
				'Переведём массу в килограммы: $m = ' + m + ' \\text{ г} = ' + m_kg + ' \\text{ кг}.$ ' +
				'Принимая $g = ' + g + ' \\text{ м/с}^2$, получаем: ' +
				'$$k = \\frac{' + m_kg + ' \\cdot ' + g + '}{' + x + '} = \\frac{' + F + '}{' + x + '} = ' + k + ' \\text{ Н/м}.$$ ' +
				'Таким образом, жёсткость пружины равна ' + k + ' Н/м.',
		});
	}, 1000);
})();
