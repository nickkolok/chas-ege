(function () {
	'use strict';
	retryWhileError(function () {
		NAinfo.requireApiVersion(0, 2);

		let key = '3497';
		let preference = ['findK', 'findX'];
		let rand = getSelectedPreferenceFromList(key, preference);

		let m_g = sl(100, 500, 50);
		let m_kg = m_g / 1000;
		let g = 10;
		let F = m_kg * g;

		let k, x_m, x_cm, text, answers, analys;

		if (rand === 0) {
			k = sl(100, 1000, 50);
			x_m = F / k;
			genAssert((x_m * 1000).isAlmostInteger() || (x_m * 10000).isAlmostInteger(), "Удлинение имеет слишком много знаков");
			
			text = 'Груз массой ' + m_g + ' г подвесили к пружине. Длина пружины при этом увеличилась на ' + x_m + ' м. Чему равна жёсткость пружины? Ответ дайте в Н/м.';
			answers = k;
			analys = 'По условию груз находится в равновесии, поэтому сила тяжести уравновешивается силой упругости пружины (закон Гука): $$mg = kx$$ Выразим жёсткость пружины: $$k = \\frac{mg}{x}$$ Переведём массу в килограммы: $m = ' + m_g + ' \\text{ г} = ' + m_kg + ' \\text{ кг}.$ Принимая $g = ' + g + ' \\text{ м/с}^2$, получаем: $$k = \\frac{' + m_kg + ' \\cdot ' + g + '}{' + x_m + '} = \\frac{' + F + '}{' + x_m + '} = ' + k + ' \\text{ Н/м}.$$ Таким образом, жёсткость пружины равна ' + k + ' Н/м.';
		} else {
			k = sl(10, 500, 10);
			x_cm = m_g / k;
			x_m = x_cm / 100;
			
			genAssert((x_cm * 100).isAlmostInteger(), "Удлинение в см имеет слишком много знаков после запятой");
			
			text = 'Груз массой ' + m_g + ' г подвесили на упругую пружину жёсткостью ' + k + ' Н/м. Чему при этом равно растяжение пружины? Ответ дайте в см.';
			answers = x_cm;
			analys = 'По условию груз находится в равновесии, поэтому сила тяжести уравновешивается силой упругости пружины (закон Гука): $$mg = kx$$ Выразим растяжение пружины: $$x = \\frac{mg}{k}$$ Переведём массу в килограммы: $m = ' + m_g + ' \\text{ г} = ' + m_kg + ' \\text{ кг}.$ Принимая $g = ' + g + ' \\text{ м/с}^2$, получаем: $$x = \\frac{' + m_kg + ' \\cdot ' + g + '}{' + k + '} = \\frac{' + F + '}{' + k + '} = ' + x_m + ' \\text{ м}.$$ Переведём результат в сантиметры: $' + x_m + ' \\cdot 100 = ' + x_cm + ' \\text{ см}.$$ Таким образом, растяжение пружины равно ' + x_cm + ' см.';
		}

		NAtask.setTask({
			text: text,
			answers: answers,
			analys: analys,
		});
	}, 1000);
})();
