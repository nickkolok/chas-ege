(function () {
	'use strict';
	retryWhileError(function () {
		NAinfo.requireApiVersion(0, 2);

		// Плотность керосина: 800 кг/м³ = 0.8 кг/л
		// Ответ должен быть целым числом литров
		// m = V * 0.8, где V - целое от 50 до 150 с шагом 10
		// Значит m должно быть кратно 8 и в диапазоне [40, 120]
		
		let V = sl(50, 150, 10); // объём в литрах
		let m = V * 0.8; // масса керосина в кг
		
		genAssert(m.isAlmostInteger(), "масса должна быть целым числом");

		NAtask.setTask({
			text: 'Топливный бак трактора вмещает ' + m + ' кг керосина. ' +
				'Чему равна ёмкость бака? Ответ запишите в литрах.',
			answers: V,
			analys: 'Для решения задачи используем формулу связи массы и объёма через плотность: ' +
				'$V = \\frac{m}{\\rho}$. ' +
				'Плотность керосина составляет $\\rho = 800$ кг/м$^3 = 0{,}8$ кг/л. ' +
				'Тогда объём бака: ' +
				'$$V = \\frac{' + m + '}{0{,}8} = ' + V + ' \\text{ л}.$$ ' +
				'Таким образом, ёмкость бака составляет $' + V + '$ литров.',
		});
	}, 1000);
})();
