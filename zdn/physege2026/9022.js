(function () {
	'use strict';
	retryWhileError(function () {
		NAinfo.requireApiVersion(0, 2);

		let Q1 = sl(50, 2000, 10);
		let A = sl(10, Q1 - 10, 5);
		let eta = (A / Q1 * 100).round();

		NAtask.setTask({
			text: 'Рабочее тело тепловой машины за цикл получает от нагревателя ' +
				'количество теплоты, равное $' + Q1 + '$ Дж, и совершает работу $' + A + '$ Дж. ' +
				'Каков КПД тепловой машины? Ответ дайте в процентах, округлив до целого.',
			answers: eta,
			analys: 'КПД тепловой машины определяется как отношение полезной работы к количеству ' +
				'теплоты, полученному от нагревателя, выраженное в процентах: ' +
				'$$\\eta = \\frac{A}{Q_1} \\cdot 100\\% = \\frac{' + A + '}{' + Q1 + '} \\cdot 100\\% = ' +
				(A / Q1 * 100).toFixed(1) + '\\% \\approx ' + eta + '\\%.$$ ' +
				'Таким образом, КПД машины составляет $' + eta + '\\%$.',
		});
	}, 1000);
})();
