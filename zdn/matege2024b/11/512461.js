(function () {
	'use strict';
	retryWhileError(function () {
		NAinfo.requireApiVersion(0, 2);

		let ans = sl(5, 20, 1);
		let k = sl(2, 3, 1);
		let k2 = k * k;
		let h = ans * k2;

		let kWord = k === 2 ? 'вдвое' : 'в ' + k + ' раза';
		let k2Word = k2 === 4 ? '4 раза' : k2 + ' раз';

		let forms = [
			'правильной треугольной призмы',
			'правильной четырёхугольной призмы',
			'правильной шестиугольной призмы'
		];
		let form = forms.iz();

		let text = 'Вода в сосуде, имеющем форму ' + form + ', находится на уровне $' + h + '$ см. ' +
		           'На каком уровне окажется вода, если её перелить в другой сосуд, имеющий форму ' + form + ', ' +
		           'у которого сторона основания ' + kWord + ' больше, чем у данного? Ответ дайте в сантиметрах.';

		let analys = 'Объем воды в первом сосуде равен $V = S \\cdot h$, где $S$ — площадь основания, $h$ — уровень воды. ' +
		             'Площадь основания правильного многоугольника пропорциональна квадрату его стороны. ' +
		             'Если сторона основания второго сосуда в $' + k + '$ раза больше, то площадь его основания в $' + k + '^2 = ' + k2 + '$ ' + k2Word + ' больше площади основания первого сосуда. ' +
		             'Так как объем воды остается прежним, уровень воды во втором сосуде будет в $' + k2 + '$ ' + k2Word + ' меньше, чем в первом. ' +
		             'Таким образом, уровень воды во втором сосуде составит $' + h + ' / ' + k2 + ' = ' + ans + '$ см.';

		NAtask.setTask({
			text: text,
			answers: ans,
			analys: analys,
		});
		NAtask.modifiers.allDecimalsToStandard();
	}, 1000);
})();
