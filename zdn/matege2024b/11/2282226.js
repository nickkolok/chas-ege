(function () {
	'use strict';
	retryWhileError(function () {
		NAinfo.requireApiVersion(0, 2);

		// Покрасить нужно боковую поверхность цилиндра: развёртка - прямоугольник
		// со сторонами «длина окружности» и «длина трубы». У ФИПИ (22D2F2, AB4618
		// и дубли) длина трубы от 2 до 6 м, обхват от 14 до 46 см; длину переводим
		// в сантиметры: S = C * 100 L.
		let length = sl(2, 6);
		let girth = sl(14, 46);
		let area = girth * length * 100;

		let text = [
			'Прямолинейный участок трубы длиной $' + length + '$ м, имеющей в сечении окружность, ' +
				'необходимо покрасить снаружи (торцы трубы открыты, их красить не нужно). ' +
				'Найдите площадь поверхности, которую необходимо покрасить, если внешний обхват трубы равен $' +
				girth + '$ см. Ответ дайте в квадратных сантиметрах.',
			'Прямолинейный участок длиной $' + length + '$ м трубы, имеющей в сечении окружность, ' +
				'необходимо покрасить снаружи (торцы трубы открыты, их красить не нужно). ' +
				'Найдите площадь поверхности, которую необходимо покрасить, если длина внешней окружности трубы равна $' +
				girth + '$ см. Ответ дайте в квадратных сантиметрах.',
		].iz();

		let analys = 'Красить нужно боковую поверхность цилиндра. Её развёртка — прямоугольник, ' +
			'одна сторона которого равна длине внешней окружности трубы, а другая — длине участка: ' +
			'$' + length + '$ м $= ' + length * 100 + '$ см. Площадь равна $' + girth + ' \\cdot ' + length * 100 + ' = ' + area + '$ см$^2$.';

		NAtask.setTask({
			text: text,
			answers: area,
			analys: analys,
			authors: ['chas-ege-ellariya'],
		});
	}, 1000);
})();
