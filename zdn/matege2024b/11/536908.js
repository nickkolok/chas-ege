let V = sl(64, 512, 64); // Объем данного конуса
let ratio1 = sl(1, 3, 1); // Первая часть отношения
let ratio2 = sl(2, 5, 1); // Вторая часть отношения

// Точка делит высоту в отношении ratio1:ratio2 от вершины
// Меньший конус подобен большому с коэффициентом k = ratio1 / (ratio1 + ratio2)
// Отношение объемов равно k^3
let k = ratio1 / (ratio1 + ratio2);
let smallVolume = V * Math.pow(k, 3);

NAtask.setTask({
	text: 'Объём данного конуса равен ' + V + '. Через точку, делящую высоту конуса в отношении ' + ratio1 + ' :' + ratio2 + ', считая от вершины, проведена плоскость, параллельная основанию. Найдите объём конуса, отсекаемого от данного конуса проведённой плоскостью.',
	answers: smallVolume,
});
