(function () {
    retryWhileError(function () {
        NAinfo.requireApiVersion(0, 2);

        let key = '509393';
        let preference = ['two_times', 'three_times', 'four_times'];
        let rand = getSelectedPreferenceFromList(key, preference);

        // k - количество орлов, которое нужно выбросить
        let k = rand + 2;
        // Математическое ожидание числа бросков до k орлов равно 2*k
        let answer = 2 * k;

        NAtask.setTask({
            text: `Монету подбрасывают до тех пор, пока орёл не выпадет ${k} раза${k > 1 ? '(не обязательно подряд)' : ''}. Найдите математическое ожидание числа бросков.`,
            answers: answer,
            analys: `Обозначим за $E_n$ математическое ожидание числа дополнительных бросков, необходимых для получения $${k}$ орлов, если у нас уже есть $n$ орлов. Нам нужно найти $E_0$.` +
                `<br/>Если у нас $n$ орлов ($n < ${k}$), то следующим броском мы с вероятностью $0.5$ получим орла (перейдем в состояние $n+1$) или решку (останемся в состоянии $n$).` +
                `<br/>Уравнение: $E_n = 1 + 0.5 \\cdot E_{n+1} + 0.5 \\cdot E_n$.` +
                `<br/>Отсюда: $0.5 \\cdot E_n = 1 + 0.5 \\cdot E_{n+1} \\Rightarrow E_n = 2 + E_{n+1}$.` +
                `<br/>Граничное условие: когда орлов уже $${k}$, броски не нужны, значит $E_${k} = 0$.` +
                `<br/>Тогда:` +
                `<br/>$E_${k - 1} = 2 + E_${k} = 2$;` +
                `<br/>$E_${k - 2} = 2 + E_${k - 1} = 4$;` +
                `<br/>...` +
                `<br/>$E_0 = 2 \\cdot ${k} = ${answer}$.` +
                `<br/>Ответ: ${answer}.`
        });

        NAtask.modifiers.allDecimalsToStandard(true);
    });
})();
