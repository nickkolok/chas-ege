(function () {
	'use strict';
	retryWhileError(function () {
		NAinfo.requireApiVersion(0, 2);

		let t = sl(2, 10, 1);
		let g = 10;
		let v = g * t;

		NAtask.setTask({
			text: 'Время свободного падения камня из состояния покоя на поверхность Земли равно $' + t + '$ с. ' +
				'Какую скорость имел камень в момент падения? Сопротивлением движению пренебречь. ' +
				'Ответ напишите в м/с.',
			answers: v,
			analys: 'При свободном падении из состояния покоя начальная скорость равна нулю ($v_0 = 0$). ' +
				'Скорость тела в момент падения определяется формулой: ' +
				'$$v = gt,$$ ' +
				'где $g = 10$ м/с² — ускорение свободного падения, $t = ' + t + '$ с — время падения. ' +
				'Подставим значения: ' +
				'$$v = 10 \\cdot ' + t + ' = ' + v + ' \\text{ м/с}.$$ ' +
				'Таким образом, скорость камня в момент падения составляет $' + v + '$ м/с.',
		});
	}, 1000);
})();
