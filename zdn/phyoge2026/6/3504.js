(function () {
	'use strict';
	retryWhileError(function () {
		NAinfo.requireApiVersion(0, 2);

		// Жесткость пружины (Н/м)
		let k = sl(10, 200, 10);
		// Растяжение пружины (см)
		let x_cm = sl(2, 20, 1);
		// Переводим в метры
		let x_m = x_cm / 100;
		// Ускорение свободного падения
		let g = 10;
		// Масса груза
		let m = (k * x_m) / g;

		genAssert(m.isAlmostInteger() || m.toString().split('.')[1].length <= 2, "число не подходит");

		NAtask.setTask({
			text: 'Груз подвесили на упругую пружину жёсткостью ' + k + ' Н/м. При этом пружина растянулась на ' + x_cm + ' см. Чему равна масса подвешенного груза? Ответ дайте в кг.',
			answers: m,
			analys: 'По закону Гука сила упругости равна $F = kx$, где $k$ — жёсткость пружины, $x$ — её растяжение. В состоянии равновесия сила упругости уравновешивает силу тяжести: $mg = kx$. Отсюда масса груза равна $m = \\frac{kx}{g} = \\frac{' + k + ' \\cdot ' + x_m + '}{' + g + '} = ' + m + '$ кг.',
		});
	}, 1000);
})();
