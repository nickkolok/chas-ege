'use strict';
////////////////////////////////////////////////////////////////////////
//	Неправильные формы прошедшего времени глагола.
//	Ключ - окончание формы мужского рода БЕЗ -ся,
//	значение - [женский род, средний род, множественное число].
//	Подбирается САМОЕ ДЛИННОЕ подходящее окончание (как в lxskl для существительных),
//	поэтому приставки обрабатываются сами: на+шёл -> на+шла, при+вёз -> при+везла.
//	Здесь только то, что правилом берётся НЕВЕРНО:
//	нёс -> нёсла, вёз -> вёзла, жёг -> жёгла, шёл -> шёла, вёл -> вёла.
//	мог -> могла, рос -> росла, тёр -> тёрла, мёрз -> мёрзла, умер -> умерла
//	правилом берутся верно, поэтому в таблицу не выписаны.
//	Окончание -ёк обобщено на весь класс глаголов на -ечь (пёк, сёк, тёк, влёк, -рёк):
//	в женском роде ударение уходит на -ла, поэтому ударной ё в основе не бывает —
//	всегда -екла/-екло/-екли. Проверено по МАС: пёк-пекла, тёк-текла, сёк-секла,
//	влёк-влекла, изрёк-изрекла. Формы без ё (выпек, высек) берутся обычным правилом.
//	А -ёг однородным не является: жёг -> жгла (гласная выпадает), но лёг -> легла
//	и берёг -> берегла, поэтому эти окончания перечислены отдельно.
////////////////////////////////////////////////////////////////////////
var lxglagol = {
	'шёл':  ['шла',    'шло',    'шли'],
	'вёл':  ['вела',   'вело',   'вели'],
	'плёл': ['плела',  'плело',  'плели'],
	'мёл':  ['мела',   'мело',   'мели'],
	'брёл': ['брела',  'брело',  'брели'],
	'счёл': ['сочла',  'сочло',  'сочли'],
	'чёл':  ['чла',    'чло',    'чли'],
	'нёс':  ['несла',  'несло',  'несли'],
	'вёз':  ['везла',  'везло',  'везли'],
	'ёк':   ['екла',   'екло',   'екли'],
	'жёг':  ['жгла',   'жгло',   'жгли'],
	'лёг':  ['легла',  'легло',  'легли'],
	'рёг':  ['регла',  'регло',  'регли'],
	'рёб':  ['ребла',  'ребло',  'ребли'],
};

//Порядок вычисляется один раз при загрузке: от длинных окончаний к коротким
var lxglagolEndings = Object.keys(lxglagol).sort(function(a, b) {
	return b.length - a.length;
});
