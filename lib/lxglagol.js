//	Неправильные формы прошедшего времени глагола.
//	Ключ - окончание формы мужского рода БЕЗ -ся,
//	значение - [женский род, средний род, множественное число].
//	Подбирается САМОЕ ДЛИННОЕ подходящее окончание (как в lxskl для существительных),
//	поэтому приставки обрабатываются сами: на+шёл -> на+шла, при+вёз -> при+везла.
//	Здесь только то, что правилом берётся НЕВЕРНО:
//	нёс -> нёсла, вёз -> вёзла, жёг -> жёгла, шёл -> шёла, вёл -> вёла.
//	мог -> могла, рос -> росла, тёр -> тёрла, мёрз -> мёрзла, умер -> умерла
//	правилом берутся верно, поэтому в таблицу не выписаны.
//	Окончание -ёк обобщено на весь класс глаголов на -ечь (пёк, сёк, тёк, влёк, -рёк):
//	в женском роде ударение уходит на -ла, поэтому ударной ё в основе не бывает —
//	всегда -екла/-екло/-екли. Проверено по МАС: пёк-пекла, тёк-текла, сёк-секла,
//	влёк-влекла, изрёк-изрекла. Формы без ё (выпек, высек) берутся обычным правилом.
//	Но под окончание -ёк попадает и блёк (блёкнуть - не на -ечь): там ударение
//	остаётся на корне и ё сохраняется (блёкла, поблёкла), поэтому блёк выписан отдельно.
//	Запись блёк срабатывает и на облёк (о+блёк), где нужно облекла, а облёк -
//	на поблёк (п+облёк), поэтому выписаны все три.
//	А -ёг однородным не является: жёг -> жгла (гласная выпадает), но лёг -> легла
//	и берёг -> берегла, поэтому эти окончания перечислены отдельно.
//	Ё в шаблонах пишут не всегда (шел и шёл встречаются одинаково часто),
//	а после ударной приставки вы- её не бывает вовсе (вышел, вычел, выжег).
//	Формы без ё выписаны только там, где правило ошибается и без ё:
//	шел -> шела, чел -> чела, жег -> жегла. Остальные (вел, нес, вез, пек, лег,
//	берег, греб) правилом берутся верно: вел -> вела, нес -> несла.
//	отпёр (отпереть) -> отперла: ё здесь только в мужском роде, а пёр -> пёрла,
//	упёр -> упёрла сохраняют её, поэтому выписан один этот глагол.
//	После приставок на согласный у жечь появляется о: сжёг -> сожгла,
//	поджёг -> подожгла, обжёг -> обожгла, разжёг -> разожгла, отжёг -> отожгла,
//	изжёг -> изожгла (но зажёг -> зажгла, выжег -> выжгла - по записи жёг/жег).
//	Так же расчёл -> разочла: запись счёл дала бы ра+сочла.
////////////////////////////////////////////////////////////////////////
